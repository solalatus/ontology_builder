// THE FINAL SCORES: every benchmark domain, 3 runs each, at the shipped state
//
//   node tests/evals/analyze-final-scores.mjs [--write]
//
// One table for all five domains, all at the same configuration: the shipped
// interviewer after #187/#188 (naming at confirmation time, rename tool, the
// stopping rule), default effort `high`, the interview to its own wrap-up,
// scored as snapshot A. fibo-loans and brick-hvac come from
// results/default-change-187/treatment/, the other three from
// results/final-scores/runs/. Descriptive, no pass criteria (see that
// directory's DESIGN.md). Adds the interviewer-first identifier count per run
// (the contamination check, lib/interviewerPriorKnowledge.mjs), so the
// unpublished itops domain can be read against the published four. --write
// saves REPORT.md and summary.json in results/final-scores/.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import { snapshotRow, mean, stdev } from "./analyze-paired-stages.mjs";
import { parseConversationLog } from "./lib/reportGenerator.mjs";
import { computeFirstSpeakerIdentifiers } from "./lib/interviewerPriorKnowledge.mjs";
import { collectMultiSegmentIdentifiers } from "./lib/leakDetector.mjs";
import { resolveDomainYamlPath, loadGroundTruthModel } from "./lib/groundTruthModel.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const RESULTS = path.resolve(__dirname, "..", "..", "ontology_translation", "results");

// Published ontologies first, then the hand-authored, never-published one.
export const DOMAINS = [
  { id: "fibo-loans", source: "FIBO (published)", dir: path.join(RESULTS, "default-change-187", "treatment") },
  { id: "brick-hvac", source: "Brick (published)", dir: path.join(RESULTS, "default-change-187", "treatment") },
  { id: "iof-maintenance", source: "IOF (published)", dir: path.join(RESULTS, "final-scores", "runs") },
  { id: "iof-supply-chain", source: "IOF (published)", dir: path.join(RESULTS, "final-scores", "runs") },
  { id: "itops", source: "hand-authored, unpublished (contamination control)", dir: path.join(RESULTS, "final-scores", "runs") },
];

const readJson = (p) => { try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; } };

/** Gold size: classes + relationships + properties (the composite's three dimensions). */
export function goldSize(domainId) {
  const g = loadGroundTruthModel({ format: "domain-yaml", path: resolveDomainYamlPath(domainId) });
  return { classes: Object.keys(g.classes).length, relationships: g.relationships.length, properties: g.properties.length };
}

export function interviewerFirstCount(runDir, domainId) {
  const logPath = path.join(runDir, "conversation-log.md");
  if (!fs.existsSync(logPath)) return null;
  const doc = yaml.load(fs.readFileSync(resolveDomainYamlPath(domainId), "utf8"));
  const { interviewerFirst, personaFirst } = computeFirstSpeakerIdentifiers(parseConversationLog(fs.readFileSync(logPath, "utf8")), collectMultiSegmentIdentifiers(doc));
  return { interviewerFirst: interviewerFirst.size, personaFirst: personaFirst.size };
}

export function loadDomainRuns(domain) {
  const runs = [];
  if (!fs.existsSync(domain.dir)) return runs;
  for (const runId of fs.readdirSync(domain.dir).filter((d) => /^run-\d+$/.test(d)).sort()) {
    const runDir = path.join(domain.dir, runId, domain.id);
    const prov = readJson(path.join(runDir, "provenance.json"));
    const m = readJson(path.join(runDir, "snapshots", "A", "metrics.json"));
    if (!prov) continue;
    runs.push({
      runId, prov, row: m ? snapshotRow(m) : null, turn: m ? m.turn : null,
      clean: prov.status === "complete" && prov.stoppedReason === "stages_complete" && Boolean(m),
      contamination: interviewerFirstCount(runDir, domain.id),
    });
  }
  return runs;
}

const agg = (runs, f) => {
  const xs = runs.filter((r) => r.clean).map(f).filter((x) => typeof x === "number");
  return { mean: mean(xs), sd: stdev(xs), n: xs.length };
};
const pm = (s, digits = 3) => (s.mean === null ? "—" : `${s.mean.toFixed(digits)}${s.sd === null ? "" : ` ± ${s.sd.toFixed(digits)}`}`);

export function summarize() {
  return DOMAINS.map((d) => ({ ...d, runs: loadDomainRuns(d), gold: goldSize(d.id) }));
}

export function renderReport(domains) {
  const L = ["# Final scores: all five domains, shipped configuration", "",
    "Generated by `tests/evals/analyze-final-scores.mjs`; design in `DESIGN.md`. Mean ± sample stdev over 3 clean runs per domain. Heuristic scorer, full domain, unless marked; every snapshot scored the same way (#182).", ""];

  L.push("## Headline", "", "| Domain | Source | Composite | Practical scope | Semantic | Class F1 | Relationship F1 | Property F1 | Rules F1 | Actions F1 |", "|---|---|---|---|---|---|---|---|---|---|");
  for (const d of domains) {
    const a = (k) => pm(agg(d.runs, (r) => r.row[k]));
    L.push(`| ${d.id} | ${d.source} | ${a("composite")} | ${a("scopedComposite")} | ${a("semanticComposite")} | ${a("classF1")} | ${a("relF1")} | ${a("propF1")} | ${a("rulesF1")} | ${a("actionsF1")} |`);
  }
  const macro = (k, set) => mean(set.map((d) => agg(d.runs, (r) => r.row[k]).mean).filter((x) => typeof x === "number"));
  const published = domains.filter((d) => d.id !== "itops");
  const fmt = (x) => (typeof x === "number" ? x.toFixed(3) : "—");
  L.push(`| **macro mean, all five** | | **${fmt(macro("composite", domains))}** | ${fmt(macro("scopedComposite", domains))} | ${fmt(macro("semanticComposite", domains))} | ${fmt(macro("classF1", domains))} | ${fmt(macro("relF1", domains))} | ${fmt(macro("propF1", domains))} | ${fmt(macro("rulesF1", domains))} | ${fmt(macro("actionsF1", domains))} |`);
  L.push(`| macro mean, four published | | ${fmt(macro("composite", published))} | ${fmt(macro("scopedComposite", published))} | ${fmt(macro("semanticComposite", published))} | ${fmt(macro("classF1", published))} | ${fmt(macro("relF1", published))} | ${fmt(macro("propF1", published))} | ${fmt(macro("rulesF1", published))} | ${fmt(macro("actionsF1", published))} |`, "");

  L.push("## Recall and precision", "", "| Domain | Gold classes / relationships / properties | Class R / P | Relationship R / P | Property R / P | Allowed-value lists |", "|---|---|---|---|---|---|");
  for (const d of domains) {
    const a = (k) => pm(agg(d.runs, (r) => r.row[k]), 2);
    L.push(`| ${d.id} | ${d.gold.classes} / ${d.gold.relationships} / ${d.gold.properties} | ${a("classRecall")} / ${a("classPrecision")} | ${a("relRecall")} / ${a("relPrecision")} | ${a("propRecall")} / ${a("propPrecision")} | ${pm(agg(d.runs, (r) => r.row.allowedValueLists), 1)} |`);
  }
  L.push("");

  L.push("## Contamination check", "", "Interviewer-first raw gold identifiers per run: a multi-segment gold identifier the interviewer said before the expert ever did (`lib/interviewerPriorKnowledge.mjs`). If the interviewer were reciting published ontologies from memory, the published domains would show many more of these than itops, which cannot have been memorized. Persona-first must be 0 (the leak guard).", "",
    "| Domain | Interviewer-first per run | per 100 gold elements | Persona-first (total) |", "|---|---|---|---|");
  for (const d of domains) {
    const s = agg(d.runs, (r) => r.contamination && r.contamination.interviewerFirst);
    const size = d.gold.classes + d.gold.relationships + d.gold.properties;
    const per100 = s.mean === null ? "—" : (100 * s.mean / size).toFixed(1);
    const pf = d.runs.reduce((n, r) => n + ((r.contamination && r.contamination.personaFirst) || 0), 0);
    L.push(`| ${d.id} | ${pm(s, 1)} | ${per100} | ${pf} |`);
  }
  L.push("");

  L.push("## Runs", "", "| Domain | Run | Stopped | Turn of wrap-up | Effort | Wall clock | Cost USD | Cached share |", "|---|---|---|---|---|---|---|---|");
  let total = 0;
  for (const d of domains) for (const r of d.runs) {
    total += r.prov.totalCostUsd || 0;
    L.push(`| ${d.id} | ${r.runId} | ${r.prov.stoppedReason}${r.clean ? "" : " (excluded)"} | ${r.turn ?? "—"} | ${r.prov.reasoningEffort} | ${Math.round((r.prov.wallClockSec || 0) / 60)} min | ${typeof r.prov.totalCostUsd === "number" ? r.prov.totalCostUsd.toFixed(2) : "—"} | ${typeof r.prov.cachedShare === "number" ? r.prov.cachedShare.toFixed(3) : "—"} |`);
  }
  L.push("", `Total: ${total.toFixed(2)} USD over ${domains.reduce((n, d) => n + d.runs.length, 0)} runs.`, "");
  return L.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const domains = summarize();
  const report = renderReport(domains);
  console.log(report);
  if (process.argv.includes("--write")) {
    const dir = path.join(RESULTS, "final-scores");
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "REPORT.md"), `${report}\n`);
    fs.writeFileSync(path.join(dir, "summary.json"), `${JSON.stringify({ generatedAt: new Date().toISOString(),
      domains: domains.map((d) => ({ id: d.id, source: d.source, gold: d.gold, runs: d.runs.map((r) => ({ runId: r.runId, clean: r.clean, turn: r.turn, row: r.row, contamination: r.contamination, cost: r.prov.totalCostUsd })) })) }, null, 2)}\n`);
  }
}
