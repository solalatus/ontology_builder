// THE BASELINES AGAINST THE FINAL SCORES, from saved runs only
//
//   node tests/evals/analyze-baselines.mjs [--write]
//
// Interactive: the final-score runs (the shipped app, snapshot A at the
// interviewer's own wrap-up; analyze-final-scores.mjs). B1, B2, B3:
// results/baselines-gpt6/<condition>/run-NN/<domain>/, each scored the same
// way (lib/snapshotScoring.mjs). Applies the reading rule pre-registered in
// results/baselines-gpt6/DESIGN.md: on a domain, interactive beats a
// baseline when the difference of mean composites exceeds the larger of the
// two stdevs, is level within it, and the baseline is ahead otherwise.
// --write saves REPORT.md and summary.json in results/baselines-gpt6/.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { snapshotRow, mean, stdev } from "./analyze-paired-stages.mjs";
import { DOMAINS as FINAL_DOMAINS } from "./analyze-final-scores.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const RESULTS = path.resolve(__dirname, "..", "..", "ontology_translation", "results");
const BASE = path.join(RESULTS, "baselines-gpt6");

export const CONDITIONS = [
  { id: "interactive", label: "Interactive (final scores)", cleanStop: "stages_complete" },
  { id: "b1-one-shot", label: "B1 one-shot", cleanStop: "extracted" },
  { id: "b2-generic-interviewer", label: "B2 generic interviewer", cleanStop: "stages_complete" },
  { id: "b3-no-commit", label: "B3 no commits", cleanStop: "stages_complete" },
];
export const DOMAINS = FINAL_DOMAINS.map((d) => ({ id: d.id, source: d.source, interactiveDir: d.dir }));

const readJson = (p) => { try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; } };

/** Every run of one condition on one domain, with its snapshot-A row. */
export function loadRuns(conditionId, domain, base = BASE) {
  const cond = CONDITIONS.find((c) => c.id === conditionId);
  const dir = conditionId === "interactive" ? domain.interactiveDir : path.join(base, conditionId);
  if (!fs.existsSync(dir)) return [];
  const runs = [];
  for (const runId of fs.readdirSync(dir).filter((d) => /^run-\d+$/.test(d)).sort()) {
    const runDir = path.join(dir, runId, domain.id);
    const prov = readJson(path.join(runDir, "provenance.json"));
    if (!prov) continue;
    const m = readJson(path.join(runDir, "snapshots", "A", "metrics.json"));
    runs.push({
      runId, prov, row: m ? snapshotRow(m) : null, offlineRescoreAgrees: m ? m.offlineRescoreAgrees : null,
      clean: prov.status === "complete" && prov.stoppedReason === cond.cleanStop && Boolean(m),
    });
  }
  return runs;
}

export const stat = (runs, key) => {
  const xs = runs.filter((r) => r.clean).map((r) => r.row[key]).filter((x) => typeof x === "number");
  return { mean: mean(xs), sd: stdev(xs), n: xs.length };
};

/** The pre-registered reading: "beats", "level" or "ahead" (the baseline is ahead). */
export function reading(interactive, baseline) {
  if (interactive.mean === null || baseline.mean === null) return null;
  const margin = Math.max(interactive.sd || 0, baseline.sd || 0);
  const diff = interactive.mean - baseline.mean;
  return diff > margin ? "beats" : diff < -margin ? "ahead" : "level";
}

export function summarize(base = BASE) {
  return DOMAINS.map((d) => ({ ...d, runs: Object.fromEntries(CONDITIONS.map((c) => [c.id, loadRuns(c.id, d, base)])) }));
}

const pm = (s, digits = 3) => (s.mean === null ? "—" : `${s.mean.toFixed(digits)}${s.sd === null ? "" : ` ± ${s.sd.toFixed(digits)}`}`);
const signed = (x) => (x === null || x === undefined ? "—" : `${x >= 0 ? "+" : ""}${x.toFixed(3)}`);

export function renderReport(domains) {
  const L = ["# Baselines at the shipped configuration: results", "",
    "Generated by `tests/evals/analyze-baselines.mjs`; design in `DESIGN.md`. Mean ± sample stdev over clean runs. Heuristic scorer, full domain, unless marked. Every condition's snapshot A is scored the same way.", ""];

  L.push("## Composite by condition", "", `| Domain | ${CONDITIONS.map((c) => c.label).join(" | ")} |`, `|---|${CONDITIONS.map(() => "---").join("|")}|`);
  for (const d of domains) L.push(`| ${d.id} | ${CONDITIONS.map((c) => pm(stat(d.runs[c.id], "composite"))).join(" | ")} |`);
  const published = domains.filter((d) => d.id !== "itops");
  const macro = (set, cid, key = "composite") => mean(set.map((d) => stat(d.runs[cid], key).mean).filter((x) => typeof x === "number"));
  const fmt = (x) => (typeof x === "number" ? x.toFixed(3) : "—");
  L.push(`| **macro, four published (primary)** | ${CONDITIONS.map((c) => `**${fmt(macro(published, c.id))}**`).join(" | ")} |`);
  L.push(`| macro, all five | ${CONDITIONS.map((c) => fmt(macro(domains, c.id))).join(" | ")} |`, "");

  L.push("## Pre-registered reading", "", "Interactive minus baseline, composite; *beats* when the difference exceeds the larger stdev, *level* within it, *ahead* when the baseline is higher by more.", "",
    `| Domain | ${CONDITIONS.slice(1).map((c) => c.label).join(" | ")} |`, `|---|${CONDITIONS.slice(1).map(() => "---").join("|")}|`);
  const tally = Object.fromEntries(CONDITIONS.slice(1).map((c) => [c.id, { beats: 0, level: 0, ahead: 0, missing: 0 }]));
  for (const d of domains) {
    const i = stat(d.runs.interactive, "composite");
    L.push(`| ${d.id} | ${CONDITIONS.slice(1).map((c) => {
      const b = stat(d.runs[c.id], "composite");
      const r = reading(i, b);
      tally[c.id][r || "missing"]++;
      return r ? `${signed(i.mean - b.mean)} (${r})` : "—";
    }).join(" | ")} |`);
  }
  L.push(`| **interactive beats / level / baseline ahead** | ${CONDITIONS.slice(1).map((c) => { const t = tally[c.id]; return `${t.beats} / ${t.level} / ${t.ahead}${t.missing ? ` (${t.missing} missing)` : ""}`; }).join(" | ")} |`, "");

  L.push("## B1 paired with the interview it read", "", "B1's run-NN extracts from the transcript of interactive run-NN on the same domain, so this difference holds the conversation fixed.", "",
    "| Domain | run-01 | run-02 | run-03 | Mean |", "|---|---|---|---|---|");
  for (const d of domains) {
    const diffs = ["run-01", "run-02", "run-03"].map((rid) => {
      const a = d.runs.interactive.find((r) => r.runId === rid && r.clean), b = d.runs["b1-one-shot"].find((r) => r.runId === rid && r.clean);
      return a && b ? b.row.composite - a.row.composite : null;
    });
    const ok = diffs.filter((x) => x !== null);
    L.push(`| ${d.id} | ${diffs.map(signed).join(" | ")} | ${ok.length ? signed(mean(ok)) : "—"} |`);
  }
  L.push("", "(B1 minus interactive: negative means the interview's own model is better.)", "");

  const measures = [["scopedComposite", "Practical scope"], ["semanticComposite", "Semantic"], ["classF1", "Class F1"], ["relF1", "Relationship F1"], ["propF1", "Property F1"], ["rulesF1", "Rules F1"], ["actionsF1", "Actions F1"]];
  for (const d of domains) {
    L.push(`## ${d.id}`, "", `| Measure | ${CONDITIONS.map((c) => c.label).join(" | ")} |`, `|---|${CONDITIONS.map(() => "---").join("|")}|`);
    for (const [k, name] of [["composite", "Composite"], ...measures]) L.push(`| ${name} | ${CONDITIONS.map((c) => pm(stat(d.runs[c.id], k))).join(" | ")} |`);
    L.push("");
  }

  L.push("## Runs", "", "| Condition | Domain | Run | Stopped | Turns | Wall clock | Cost USD | Offline replay |", "|---|---|---|---|---|---|---|---|");
  let total = 0, n = 0;
  for (const c of CONDITIONS.slice(1)) for (const d of domains) for (const r of d.runs[c.id]) {
    total += r.prov.totalCostUsd || 0; n++;
    L.push(`| ${c.id} | ${d.id} | ${r.runId} | ${r.prov.stoppedReason}${r.clean ? "" : " (excluded)"} | ${r.prov.turnsUsed ?? "—"} | ${Math.round((r.prov.wallClockSec || 0) / 60)} min | ${typeof r.prov.totalCostUsd === "number" ? r.prov.totalCostUsd.toFixed(2) : "—"} | ${r.offlineRescoreAgrees === true ? "agrees" : r.offlineRescoreAgrees === false ? "DIFFERS" : "—"} |`);
  }
  L.push("", `Total for the baselines: ${total.toFixed(2)} USD over ${n} runs.`, "");
  return L.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const domains = summarize();
  const report = renderReport(domains);
  console.log(report);
  if (process.argv.includes("--write")) {
    fs.writeFileSync(path.join(BASE, "REPORT.md"), `${report}\n`);
    fs.writeFileSync(path.join(BASE, "summary.json"), `${JSON.stringify({
      generatedAt: new Date().toISOString(),
      domains: domains.map((d) => ({ id: d.id, conditions: Object.fromEntries(Object.entries(d.runs).map(([cid, runs]) => [cid, {
        composite: stat(runs, "composite"), runs: runs.map((r) => ({ runId: r.runId, clean: r.clean, row: r.row, cost: r.prov.totalCostUsd })),
      }])) })),
    }, null, 2)}\n`);
  }
}
